/**
 * Единая точка редактирования числовых tuning-параметров игровой логики —
 * скорости, размеры, интервалы спавна, длительности эффектов и т.п.
 *
 * По запросу пользователя после фидбека по фиче 002 (спавн/движение
 * насекомых и бонусов): раньше эти числа были разбросаны по отдельным
 * game/*.ts-модулям, что затрудняло балансировку игры «одним взглядом».
 *
 * Архитектурно ничего не меняется (принцип I конституции, YAGNI — никакого
 * фреймворка конфигурации, просто именованные константы): каждый модуль
 * (frog.ts, insects.ts, bonuses.ts, effects.ts) по-прежнему сам решает, как
 * использовать своё значение, и продолжает экспортировать его под тем же
 * именем через `export { X } from './tuning'` — импорты во внешнем коде
 * (тесты, другие модули) не меняются. Здесь собраны только сами числа, не
 * логика.
 *
 * Константы, не являющиеся продуктовым tuning-параметром (например,
 * `JUMP_LANDING_EPSILON_S` в frog.ts — технический эпсилон плавающей точки,
 * а не число, которое имеет смысл двигать балансируя геймплей), сюда
 * намеренно не вынесены и остаются внутри своего модуля.
 */

